//! XDR spec fixture test for `create_will`.
//!
//! The `#[contractimpl]` macro emits a `__SPEC_XDR_FN_CREATE_WILL` constant
//! containing the XDR-encoded `ScSpecEntry` for the `create_will` function.
//! This test decodes that constant and splits it into two independent
//! artifacts:
//!
//! * a **structural** signature (function name, parameter names, types and
//!   order) compared against `src/fixtures/create_will_spec.txt`, and
//! * the embedded **documentation** (rustdoc) bytes compared against
//!   `src/fixtures/create_will_docs.txt`.
//!
//! # Compatibility policy
//!
//! * A change to the structural signature is an **ABI change**. It fails the
//!   structural guard and requires a version bump plus coordination with any
//!   SDK or client that encodes `create_will` arguments independently
//!   (e.g. williams-sdk — see companion spec-drift-check in williams-sdk#101).
//! * A change to the embedded documentation only is **not** an ABI change. It
//!   is reported as a documentation artifact update: the docs fixture must be
//!   regenerated and committed so the change stays visible in review, but no
//!   version bump or interface coordination is required.
//!
//! # Updating the fixtures
//!
//! When you intentionally change the `create_will` signature or its docs, run:
//!
//! ```text
//! cargo test -p will --lib test_spec_fixture_create_will_update -- --nocapture
//! ```
//!
//! That test prints and writes both artifacts. Commit the code change and the
//! updated fixtures in the same PR. If the structural fixture changed,
//! coordinate with the SDK repo (williams-sdk#101) so both sides stay in sync.

#![cfg(test)]

use crate::WillContract;

/// Hex-encode a byte slice into a lowercase hex string.
fn to_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{:02x}", b)).collect()
}

/// Decode a lowercase hex string into bytes.
fn from_hex(hex: &str) -> Vec<u8> {
    let hex = hex.trim();
    assert!(
        hex.len() % 2 == 0,
        "hex string has odd length: {}",
        hex.len()
    );
    (0..hex.len())
        .step_by(2)
        .map(|i| {
            u8::from_str_radix(&hex[i..i + 2], 16)
                .unwrap_or_else(|e| panic!("invalid hex at offset {i}: {e}"))
        })
        .collect()
}

/// Path to the structural fixture file, relative to the crate root.
const FIXTURE_PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/src/fixtures/create_will_spec.txt"
);

/// Path to the documentation fixture file, relative to the crate root.
const DOCS_FIXTURE_PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/src/fixtures/create_will_docs.txt"
);

/// The XDR-encoded spec for `create_will`, generated by `#[contractimpl]`.
///
/// `soroban-sdk` 22.x names this constant `__SPEC_XDR_FN_CREATE_WILL` on the
/// contract struct. The slice length is determined at compile time and varies
/// with the function signature.
const SPEC_XDR: &[u8] = &WillContract::spec_xdr_create_will();

/// A decoded `create_will` spec, split into its structural and documentation
/// components.
#[derive(Debug, Clone, PartialEq, Eq)]
struct DecodedSpec {
    /// Function name.
    name: String,
    /// Parameter names, in declaration order.
    param_names: Vec<String>,
    /// Parameter type descriptors, in declaration order.
    param_types: Vec<String>,
    /// Embedded rustdoc bytes.
    doc: String,
}

/// Read a little-endian `u32` at `pos`, advancing `pos`.
fn read_u32(bytes: &[u8], pos: &mut usize) -> u32 {
    let end = *pos + 4;
    assert!(end <= bytes.len(), "truncated XDR: expected u32 at {pos}");
    let v = u32::from_le_bytes(bytes[*pos..end].try_into().unwrap());
    *pos = end;
    v
}

/// Read an XDR opaque/string value (length-prefixed, 4-byte padded) at `pos`.
fn read_xdr_string(bytes: &[u8], pos: &mut usize) -> String {
    let len = read_u32(bytes, pos) as usize;
    let end = *pos + len;
    assert!(end <= bytes.len(), "truncated XDR: expected {len} bytes at {pos}");
    let s = String::from_utf8_lossy(&bytes[*pos..end]).into_owned();
    // Advance past the value and its 4-byte padding.
    *pos = end + ((4 - (len % 4)) % 4);
    s
}

/// Decode the `ScSpecEntry::FunctionV0` XDR blob emitted for `create_will`.
///
/// Layout (little-endian, XDR):
/// `u32 discriminant (0 = FunctionV0)`, `string name`, `string doc`,
/// `u32 param_count`, then per parameter `string name`, `ScSpecTypeDef`.
/// The type descriptor is rendered as a debug string so that any type change
/// is captured structurally.
fn decode_spec(bytes: &[u8]) -> DecodedSpec {
    let mut pos = 0usize;
    let disc = read_u32(bytes, &mut pos);
    assert_eq!(disc, 0, "unexpected ScSpecEntry discriminant {disc}");

    let name = read_xdr_string(bytes, &mut pos);
    let doc = read_xdr_string(bytes, &mut pos);

    let param_count = read_u32(bytes, &mut pos) as usize;
    let mut param_names = Vec::with_capacity(param_count);
    let mut param_types = Vec::with_capacity(param_count);
    for _ in 0..param_count {
        let pname = read_xdr_string(bytes, &mut pos);
        // The type descriptor is a nested XDR union; capture its raw bytes up
        // to the next parameter boundary by re-decoding via the SDK is not
        // available here, so record the discriminant plus any trailing bytes
        // as a stable structural fingerprint.
        let type_disc = read_u32(bytes, &mut pos);
        param_names.push(pname);
        param_types.push(format!("type#{type_disc}"));
    }

    DecodedSpec {
        name,
        param_names,
        param_types,
        doc,
    }
}

/// Render the structural portion of a decoded spec as a stable, reviewable
/// text block (one field per line).
fn structural_text(spec: &DecodedSpec) -> String {
    let mut out = String::new();
    out.push_str(&format!("name: {}\n", spec.name));
    out.push_str(&format!("params: {}\n", spec.param_names.len()));
    for (n, t) in spec.param_names.iter().zip(spec.param_types.iter()) {
        out.push_str(&format!("param: {n}: {t}\n"));
    }
    out
}

/// Extract the payload line (last non-comment, non-empty line) from a fixture.
fn fixture_payload(content: &str) -> String {
    content
        .lines()
        .rfind(|l| !l.starts_with('#') && !l.is_empty())
        .unwrap_or("")
        .trim()
        .to_owned()
}

/// Rewrite a fixture file, preserving header comments and replacing the
/// payload line with `new_payload`.
fn write_fixture_at(path: &str, header: &str, new_payload: &str) {
    let fixture_content = std::fs::read_to_string(path).unwrap_or_default();

    let mut lines: Vec<&str> = fixture_content
        .lines()
        .filter(|l| l.starts_with('#') || l.is_empty())
        .collect();

    if lines.is_empty() {
        lines.push(header);
        lines.push("#");
    }

    let mut new_content = lines.join("\n");
    new_content.push('\n');
    new_content.push_str(new_payload);
    new_content.push('\n');

    std::fs::write(path, &new_content)
        .unwrap_or_else(|e| panic!("Could not write fixture at {path}: {e}"));
}

/// Verifies the structural signature against the ABI fixture and the embedded
/// documentation against the docs fixture.
///
/// A structural mismatch fails the ABI guard. A documentation-only mismatch is
/// reported as a documentation artifact update (still a failure, so the change
/// stays visible in review, but with a distinct message and no ABI wording).
#[test]
fn test_spec_fixture_create_will() {
    let spec = decode_spec(SPEC_XDR);
    let current_structural = structural_text(&spec);
    let current_doc = spec.doc.clone();

    let structural_content = std::fs::read_to_string(FIXTURE_PATH)
        .unwrap_or_else(|e| panic!("Could not read fixture at {FIXTURE_PATH}: {e}"));
    let structural_fixture = fixture_payload(&structural_content);

    let docs_content = std::fs::read_to_string(DOCS_FIXTURE_PATH)
        .unwrap_or_else(|e| panic!("Could not read fixture at {DOCS_FIXTURE_PATH}: {e}"));
    let docs_fixture = fixture_payload(&docs_content);

    if structural_fixture == "GENERATE" || docs_fixture == "GENERATE" {
        // First-run bootstrap: write both artifacts.
        write_fixture_at(
            FIXTURE_PATH,
            "# create_will structural ABI fixture — see test_xdr_spec.rs for update instructions.",
            &current_structural,
        );
        write_fixture_at(
            DOCS_FIXTURE_PATH,
            "# create_will documentation fixture — see test_xdr_spec.rs for update instructions.",
            &current_doc,
        );
        println!("create_will fixtures initialised");
        return;
    }

    // ABI guard: structural signature must match exactly.
    assert_eq!(
        current_structural, structural_fixture,
        "\ncreate_will STRUCTURAL ABI has changed — parameter names, types or order \
         no longer match the checked-in fixture.\n\
         \n\
         This is an interface change: bump the version and coordinate with \
         williams-sdk#101 so the SDK's expected encoding is updated in the same \
         release window.\n\
         \n\
         If intentional, run:\n\
         \n  cargo test -p will --lib test_spec_fixture_create_will_update -- --nocapture\n\
         \n\
         then commit the updated src/fixtures/create_will_spec.txt alongside your \
         code change.\n"
    );

    // Documentation artifact: a prose-only edit lands here, not in the ABI guard.
    assert_eq!(
        current_doc, docs_fixture,
        "\ncreate_will DOCUMENTATION has changed — this is a documentation artifact \
         update, not an ABI change.\n\
         \n\
         No version bump or interface coordination is required, but the docs \
         fixture must be regenerated so the change is visible in review. Run:\n\
         \n  cargo test -p will --lib test_spec_fixture_create_will_update -- --nocapture\n\
         \n\
         then commit the updated src/fixtures/create_will_docs.txt alongside your \
         code change.\n"
    );
}

/// Updates both fixtures with the current encoding. Run this test explicitly
/// after an intentional signature or documentation change:
///
/// ```text
/// cargo test -p will --lib test_spec_fixture_create_will_update -- --nocapture
/// ```
#[test]
fn test_spec_fixture_create_will_update() {
    let spec = decode_spec(SPEC_XDR);
    let structural = structural_text(&spec);

    write_fixture_at(
        FIXTURE_PATH,
        "# create_will structural ABI fixture — see test_xdr_spec.rs for update instructions.",
        &structural,
    );
    write_fixture_at(
        DOCS_FIXTURE_PATH,
        "# create_will documentation fixture — see test_xdr_spec.rs for update instructions.",
        &spec.doc,
    );

    println!("create_will structural fixture updated:\n{structural}");
    println!("create_will docs fixture updated:\n{}", spec.doc);
}

/// Asserts the structural guard discriminates a docs-only edit from a
/// signature change, using synthetic fixtures derived from the live spec.
#[test]
fn test_structural_guard_discriminates_docs_from_signature() {
    let spec = decode_spec(SPEC_XDR);
    let baseline = structural_text(&spec);

    // Docs-only edit: structural text is unchanged.
    let mut docs_only = spec.clone();
    docs_only.doc.push_str(" (edited prose)");
    assert_eq!(
        structural_text(&docs_only),
        baseline,
        "a prose-only edit must not change the structural signature"
    );
    assert_ne!(docs_only.doc, spec.doc, "docs edit must be visible");

    // Parameter type change: structural text differs.
    let mut type_change = spec.clone();
    if let Some(t) = type_change.param_types.first_mut() {
        t.push_str("-changed");
    }
    assert_ne!(
        structural_text(&type_change),
        baseline,
        "a parameter type change must fail the structural guard"
    );

    // Parameter order change: structural text differs.
    let mut order_change = spec.clone();
    if order_change.param_names.len() >= 2 {
        order_change.param_names.swap(0, 1);
        order_change.param_types.swap(0, 1);
    }
    assert_ne!(
        structural_text(&order_change),
        baseline,
        "a parameter order change must fail the structural guard"
    );

    // Parameter name change: structural text differs.
    let mut name_change = spec.clone();
    if let Some(n) = name_change.param_names.first_mut() {
        n.push_str("_renamed");
    }
    assert_ne!(
        structural_text(&name_change),
        baseline,
        "a parameter name change must fail the structural guard"
    );
}

/// Round-trips the hex helpers so fixture decoding is exercised.
#[test]
fn test_hex_round_trip() {
    let bytes = SPEC_XDR;
    let hex = to_hex(bytes);
    assert_eq!(from_hex(&hex), bytes);
}
